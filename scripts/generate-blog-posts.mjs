#!/usr/bin/env node
/**
 * Bundles the published blog posts into lib/generated/blogPosts.ts.
 *
 * The live site runs on Cloudflare Workers, which has no project files at
 * runtime, so lib/blog.ts cannot read content/posts with fs there. It reads
 * this generated module instead. Only posts with `published: true` in their
 * frontmatter are bundled; unpublished drafts stay out of the Worker.
 *
 * Runs before every build. lib/blog.generated.test.ts fails if the
 * committed module drifts from content/posts, so after editing a post run:
 *
 *   npm run blog:generate
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const SCRIPT = fileURLToPath(import.meta.url)
const ROOT = path.resolve(path.dirname(SCRIPT), '..')
const POSTS_DIR = path.join(ROOT, 'content', 'posts')
const OUT_FILE = path.join(ROOT, 'lib', 'generated', 'blogPosts.ts')
const SLUGS_FILE = path.join(ROOT, 'lib', 'generated', 'blogSlugs.ts')

export function isPublished(source) {
  const frontmatter = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/.exec(source)
  return Boolean(frontmatter && /^published:\s*true\s*$/m.test(frontmatter[1]))
}

/** Mirrors lib/blog.ts: the frontmatter `slug`, else the file name. */
export function slugOf({ fileName, source }) {
  const frontmatter = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/.exec(source)
  const match = frontmatter && /^slug:\s*["']?([^"'\r\n]+?)["']?\s*$/m.exec(frontmatter[1])
  return match ? match[1] : fileName.replace(/\.mdx?$/, '')
}

export function readPublishedSources(postsDir = POSTS_DIR) {
  if (!fs.existsSync(postsDir)) return []
  return fs
    .readdirSync(postsDir)
    .filter((file) => file.endsWith('.mdx') || file.endsWith('.md'))
    .sort()
    .map((fileName) => ({ fileName, source: fs.readFileSync(path.join(postsDir, fileName), 'utf8') }))
    .filter(({ source }) => isPublished(source))
}

export function renderModule(sources) {
  return `// Generated by scripts/generate-blog-posts.mjs from content/posts. Do not edit.
// Run \`npm run blog:generate\` after changing a post.

export interface BlogPostSource {
  fileName: string
  source: string
}

export const BLOG_POST_SOURCES: readonly BlogPostSource[] = ${JSON.stringify(sources, null, 2)}
`
}

/**
 * The slugs alone, for middleware.ts: it answers unknown /blog/<slug> paths with
 * a real 404 and should not have to load every post's text to do that.
 */
export function renderSlugsModule(sources) {
  return `// Generated by scripts/generate-blog-posts.mjs from content/posts. Do not edit.
// Run \`npm run blog:generate\` after changing a post.

export const BLOG_POST_SLUGS: readonly string[] = ${JSON.stringify(sources.map(slugOf).sort(), null, 2)}
`
}

if (process.argv[1] && path.resolve(process.argv[1]) === SCRIPT) {
  const sources = readPublishedSources()
  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true })
  fs.writeFileSync(OUT_FILE, renderModule(sources))
  fs.writeFileSync(SLUGS_FILE, renderSlugsModule(sources))
  console.log(`blog: bundled ${sources.length} published post(s) into ${path.relative(ROOT, OUT_FILE)}`)
}
